function abrirModal() {
  const modal = document.getElementById("miModal");
  if (modal) {
    modal.style.display = "flex";
  }
}

function cerrarModal() {
  const modal = document.getElementById("miModal");
  if (modal) {
    modal.style.display = "none";
  }
}


